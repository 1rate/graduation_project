class SentimentModel:
    """Обученная модель (SentenceTransformer + LogisticRegression) без правил."""

    def __init__(self, model_path: str):
        print(f"📥 Загрузка модели из {model_path}")
        self.embedder = SentenceTransformer(
            os.path.join(model_path, "transformer")
        )
        with open(os.path.join(model_path, "classifier.pkl"), "rb") as f:
            self.clf, self.label2id, self.id2label = pickle.load(f)
        print("✅ Модель загружена")

    def predict(self, text: str) -> tuple:
        """Возвращает (label, score)."""
        emb = self.embedder.encode([text])
        pred_id = self.clf.predict(emb)[0]
        probas = self.clf.predict_proba(emb)[0]
        label = self.id2label[pred_id]
        score = float(probas[pred_id])
        return label, score


def main():
    print("=" * 80)
    print(f"🧪 ТЕСТИРОВАНИЕ МОДЕЛИ (папка {MODEL_PATH})")
    print("=" * 80)

    # Загрузка модели
    start_time = time.time()
    model = SentimentModel(MODEL_PATH)
    load_time = time.time() - start_time
    print(f"⏱  Модель загружена за {load_time:.1f}с\n")

    # Статистика
    total = 0
    passed = 0
    failed = 0
    errors = []
    by_category = defaultdict(lambda: {"total": 0, "passed": 0})

    total_time = 0.0

    for text, expected, category in TEST_CASES:
        total += 1
        by_category[category]["total"] += 1

        start = time.time()
        label, score = model.predict(text)
        pred_time = time.time() - start
        total_time += pred_time

        is_passed = (label == expected)
        if is_passed:
            passed += 1
            by_category[category]["passed"] += 1
            status = "✅"
        else:
            failed += 1
            errors.append({
                "text": text,
                "expected": expected,
                "got": label,
                "score": score,
                "category": category
            })
            status = "❌"

        print(f"{status} [{category:<20}] {text[:70]:<70} → {label} ({score:.3f})")

    # Итоги
    accuracy = passed / total * 100
    avg_time = total_time / total * 1000

    print("\n" + "=" * 80)
    print("📊 ИТОГИ")
    print("=" * 80)
    print(f"Всего тестов:     {total}")
    print(f"Пройдено:         {passed} ✅")
    print(f"Провалено:        {failed} ❌")
    print(f"Точность:         {accuracy:.1f}%")
    print(f"Среднее время:    {avg_time:.0f} мс")

    print(f"\n📊 ТОЧНОСТЬ ПО КАТЕГОРИЯМ:")
    for category in sorted(by_category.keys()):
        stats = by_category[category]
        acc = stats["passed"] / stats["total"] * 100
        bar = "█" * int(acc / 5) + "░" * (20 - int(acc / 5))
        print(f"  {category:<25} {bar} {acc:.0f}% ({stats['passed']}/{stats['total']})")

    # Сохранение результатов
    results = {
        "timestamp": datetime.now().isoformat(),
        "model": "sentence-transformer + logistic regression",
        "total": total,
        "passed": passed,
        "failed": failed,
        "accuracy": accuracy,
        "avg_time_ms": avg_time,
        "load_time_s": load_time,
        "by_category": {k: {"total": v["total"], "passed": v["passed"]}
                        for k, v in by_category.items()},
        "errors": errors
    }

    output_dir = Path("/app/output")
    output_dir.mkdir(exist_ok=True)

    output_file = output_dir / f"test_results_{datetime.now().strftime('%Y%m%d_%H%M%S')}.json"
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(results, f, ensure_ascii=False, indent=2)

    latest = output_dir / "latest_results.json"
    with open(latest, 'w', encoding='utf-8') as f:
        json.dump(results, f, ensure_ascii=False, indent=2)

    print(f"\n📁 Результаты сохранены в {output_file}")

    if failed > 0:
        print(f"\n❌ Провалено тестов: {failed}")
        sys.exit(1)
    else:
        print(f"\n✅ Все тесты пройдены!")
        sys.exit(0)


